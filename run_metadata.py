import os
from datetime import datetime
from bson.objectid import ObjectId


def read_file_metadata(fname:str):
    # Read preprocessed metadata from file.

    # Read ObjectID binary ID's
    handle_0 = open(f'{fname}.bson','rb')
    bsondat = handle_0.read()
    handle_0.close()
    bsonlist = bsondat.split(b',\n')[0:-1]
    objid = [ObjectId(b) for b in bsonlist]

    # Read info.params.programFile field
    handle_1 = open(f'{fname}_progfiles.txt','r')
    progfiles = handle_1.readlines()
    handle_1.close()
    progfilenames = [dat.strip('\n') for dat in progfiles]

    # Read _meta.logfile field
    handle_2 = open(f'{fname}_logfiles.txt','r')
    logfiles = handle_2.readlines()
    handle_2.close()
    logfilenames = [dat.strip('\n') for dat in logfiles]

    return objid, progfilenames, logfilenames

def write_file_metadata(datalist, fname):
    handle = open(f'{fname}.bson','wb')
    for dat in datalist:
        handle.write(dat['_id'].binary+b",\n")
    handle.close()

    handle = open(f'{fname}_progfiles.txt','w')
    for dat in datalist:
        handle.write(dat['info']['params']['programFile']+'\n')
    handle.close()

    handle = open(f'{fname}_logfiles.txt','w')
    for dat in datalist:
        handle.write(dat['_meta']['logfile']+'\n')
    handle.close()

def find_basenames(dirname):
    '''Gets list of run names from raw_data directory'''
    basenames = []
    for n in os.listdir(dirname):
        base,dstr,bstr,_ = n.split(sep='_')
        runname = f"{dirname}/{base}_{dstr}_{bstr}"
        if not runname in basenames:
            basenames.append(runname)

    return basenames

